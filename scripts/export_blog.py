"""Export the report as a post body for the 8KGM blog (Next.js site).

Writes `components/blog/posts/<module>.<lang>.ts` with the body as an HTML string, and copies the
embedded charts to `public/blog/<slug>/<lang>/`. Chapter headings drop one level, because the
post title is the page's h1. Needs pandoc.

    uv run python scripts/export_blog.py --site ../8kgm_website --lang es
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_informe import IFRAME, assemble

ROOT = Path(__file__).resolve().parents[1]
SLUG = "deuda-en-dos-monedas"
MODULE = "DeudaEnDosMonedas"
H2 = re.compile(r'<h2 id="([^"]+)"[^>]*>(.*?)</h2>', re.S)
TAG = re.compile(r"<[^>]+>")


def body_html(src: Path, glossary: Path, lang: str) -> tuple[str, list[str]]:
    md = assemble(src, glossary)
    charts: list[str] = []

    def iframe(m: re.Match[str]) -> str:
        kind, name, title = m.groups()
        charts.append(name)
        return (
            f'<iframe class="{kind}" src="/blog/{SLUG}/{lang}/{name}.html" '
            f'title="{title}" loading="lazy"></iframe>'
        )

    md = IFRAME.sub(iframe, md)
    html = subprocess.run(
        ["pandoc", "--from=markdown", "--to=html5", "--shift-heading-level-by=1",
         f"--metadata=lang:{lang}"],
        input=md, text=True, check=True, capture_output=True,
    ).stdout  # fmt: skip
    return html, charts


def chart_labels(path: Path) -> dict[str, str]:
    """Spanish chart string -> translation, longest first so that no label is cut by a shorter
    one it contains."""
    labels: dict[str, str] = json.loads(path.read_text(encoding="utf-8"))
    return dict(sorted(labels.items(), key=lambda kv: -len(kv[0])))


def translate_chart(page: str, labels: dict[str, str], lang: str) -> str:
    """Swap whole quoted strings (and the page title) only, so numbers and code stay intact."""
    for es, tr in labels.items():
        for q in ('"', "'"):
            page = page.replace(f"{q}{es}{q}", f"{q}{tr}{q}")
        page = page.replace(f"<title>{es}</title>", f"<title>{tr}</title>")
    return page.replace("<html lang='es'>", f"<html lang='{lang}'>")


def toc(html: str) -> list[dict[str, str]]:
    return [{"id": i, "title": " ".join(TAG.sub("", t).split())} for i, t in H2.findall(html)]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", type=Path, required=True)
    ap.add_argument("--lang", default="es")
    ap.add_argument("--src", type=Path, help="chapters (default: informe/, or informe/<lang>/)")
    ap.add_argument("--glossary", type=Path)
    ap.add_argument("--charts", type=Path, default=ROOT / "data" / "informe")
    args = ap.parse_args()
    lang = args.lang
    src = args.src or (ROOT / "informe" if lang == "es" else ROOT / "informe" / lang)
    glossary = args.glossary or (
        ROOT / "docs" / "GLOSARIO.md" if lang == "es" else ROOT / "docs" / f"GLOSARIO.{lang}.md"
    )
    html, charts = body_html(src, glossary, lang)

    out = args.site / "components" / "blog" / "posts" / f"{MODULE}.{lang}.ts"
    out.write_text(
        "// Generated by argentina-fiscalidad-divisas/scripts/export_blog.py. Do not edit.\n"
        f"export const toc = {json.dumps(toc(html), ensure_ascii=False, indent=2)};\n\n"
        f"export const html = {json.dumps(html, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    dest = args.site / "public" / "blog" / SLUG / lang
    dest.mkdir(parents=True, exist_ok=True)
    labels = chart_labels(src / "graficos.json") if lang != "es" else {}
    for name in sorted(set(charts)):
        page = args.charts / f"{name}.html"
        if not page.exists():
            raise SystemExit(f"falta el gráfico {page}")
        (dest / page.name).write_text(
            translate_chart(page.read_text(encoding="utf-8"), labels, lang), encoding="utf-8"
        )
        data = args.charts / f"{name}.csv"
        if data.exists():
            shutil.copy2(data, dest / data.name)
    print(f"{out}: {len(html):,} caracteres, {len(set(charts))} gráficos en {dest}")


if __name__ == "__main__":
    main()
